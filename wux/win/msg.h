typedef uintptr_t WParam;
typedef intptr_t  LParam;
typedef intptr_t  Result;

inline int16_t lo16(uintptr_t v) { return (int16_t)(v & 0xffff); }
inline int16_t hi16(uintptr_t v) { return (int16_t)((v >> 16) & 0xffff); }
inline LParam make_lparam(int32_t lo, int32_t hi) {
    return (LParam)(((uint32_t)hi << 16) | ((uint32_t)lo & 0xffff));
}
inline LParam lparam_of(gdi::Point p) { return make_lparam(p.x, p.y); }
inline gdi::Point point_of(LParam l) { return gdi::Point{lo16((uintptr_t)l), hi16((uintptr_t)l)}; }

